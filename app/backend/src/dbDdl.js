// Prints the SQL that db:setup would run for the active profile, so it can be read or run by hand in psql.
//   npm run db:ddl:prod > sql/production_core_init.sql
import { createSchema, createTables, INDEXES } from './spec/ddl.js';
import { describeProfile } from './db/profile.js';
const out = [`-- Database profile: ${describeProfile()}`, '-- Generated by: npm run db:ddl. Safe to re-run: every statement is IF NOT EXISTS.', ''];
out.push(...[...createSchema(), ...createTables(), ...INDEXES].map(q => q + ';'));
console.log(out.join('\n'));
